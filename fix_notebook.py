cells[50]['source'] = [
    "# %% [code]\n",
    "# 2.2 Preparação das Features para Classificação\n",
    "#\n",
    "# Usamos TODAS as 335 features (macros + tags binárias), excluindo `calories`\n",
    "# para evitar vazamento de informação.\n",
    "# Isso dá ao modelo mais sinal do que apenas as 30 features do Bloco 1,\n",
    "# aumentando a chance de capturar qualquer padrão existente no rating.\n",
    "#\n",
    "# Nota: QDA e LDA continuarão usando TOP30_FEATURES pois a inversão de matriz\n",
    "# em espaços de alta dimensão causa singularidade.\n",
    "\n",
    "X_cls_all = dados_cls[ALL_FEATURES].copy()\n",
    "X_cls_top30 = dados_cls[TOP30_FEATURES].copy()\n",
    "y_cls = dados_cls['rating_class'].copy()\n",
    "\n",
    "# Split estratificado 80/20\n",
    "from sklearn.model_selection import train_test_split as tts\n",
    "\n",
    "X_train_all, X_test_all, y_train_cls, y_test_cls = tts(\n",
    "    X_cls_all, y_cls, test_size=0.20, random_state=SEED, stratify=y_cls\n",
    ")\n",
    "X_train_top30, X_test_top30 = (\n",
    "    X_cls_top30.loc[X_train_all.index],\n",
    "    X_cls_top30.loc[X_test_all.index]\n",
    ")\n",
    "# Alias padrão: classificadores complexos usam ALL; modelos paramétricos usam TOP30\n",
    "X_train_cls, X_test_cls = X_train_all, X_test_all\n",
    "\n",
    "print(f'Treino: {len(X_train_cls):,} amostras | Teste: {len(X_test_cls):,} amostras')\n",
    "print(f'Features (all): {X_train_cls.shape[1]} | Features (top30): {X_train_top30.shape[1]}')\n",
    "\n",
    "# Função auxiliar de avaliação\n",
    "def avaliar_classificador(nome, clf, X_tr, y_tr, X_te, y_te, cv=5):\n",
    "    \"\"\"Avalia classificador via StratifiedKFold + conjunto de teste.\"\"\"\n",
    "    skf = StratifiedKFold(n_splits=cv, shuffle=True, random_state=SEED)\n",
    "    cv_acc = cross_val_score(clf, X_tr, y_tr, cv=skf, scoring='accuracy', n_jobs=-1)\n",
    "    cv_f1  = cross_val_score(clf, X_tr, y_tr, cv=skf, scoring='f1_macro',  n_jobs=-1)\n",
    "    clf.fit(X_tr, y_tr)\n",
    "    y_pred = clf.predict(X_te)\n",
    "    result = {\n",
    "        'Classificador': nome,\n",
    "        'Acurácia CV (Treino)': f'{cv_acc.mean():.4f} ± {cv_acc.std():.4f}',\n",
    "        'F1-Macro CV (Treino)': f'{cv_f1.mean():.4f} ± {cv_f1.std():.4f}',\n",
    "        'Acurácia Teste': accuracy_score(y_te, y_pred),\n",
    "        'F1-Macro Teste': f1_score(y_te, y_pred, average='macro'),\n",
    "        'clf_fitted': clf,\n",
    "        'y_pred': y_pred\n",
    "    }\n",
    "    print(f'[{nome:26s}] Acc: {result[\"Acurácia Teste\"]:.4f} | F1: {result[\"F1-Macro Teste\"]:.4f}')\n",
    "    return result\n",
    "\n",
    "resultados_classificacao = []\n",
]

